#include "v68.h"

static const u8 font[9][8] = {
    { 0x3C, 0x66, 0x66, 0x7E, 0x66, 0x66, 0x66, 0x00 },
    { 0x7E, 0x60, 0x60, 0x7C, 0x60, 0x60, 0x7E, 0x00 },
    { 0x3C, 0x66, 0x60, 0x6E, 0x66, 0x66, 0x3C, 0x00 },
    { 0x66, 0x66, 0x66, 0x7E, 0x66, 0x66, 0x66, 0x00 },
    { 0x60, 0x60, 0x60, 0x60, 0x60, 0x60, 0x7E, 0x00 },
    { 0x3C, 0x66, 0x66, 0x66, 0x66, 0x66, 0x3C, 0x00 },
    { 0x66, 0x66, 0x66, 0x66, 0x66, 0x3C, 0x18, 0x00 },
    { 0x3C, 0x66, 0x60, 0x7C, 0x66, 0x66, 0x3C, 0x00 },
    { 0x3C, 0x66, 0x66, 0x3C, 0x66, 0x66, 0x3C, 0x00 },
};

static const u8 text[12] = { 4, 2, 5, 5, 6, 0, 7, 2, 3, 1, 8, 9 };

void main(void) {
    V68_PALETTE[0] = 0x00102040;
    V68_PALETTE[1] = 0x00FFFFFF;

    for (i32 g = 0; g < 9; g++)
        for (i32 y = 0; y < 8; y++)
            for (i32 x = 0; x < 8; x++)
                V68_TILES[g + 1].px[y][x] = (font[g][y] >> (7 - x)) & 1;

    for (i32 i = 0; i < 12; i++)
        V68_TILEMAPS[0].cell[11][14 + i] = text[i];
}
