#include "vega68_hw.h"

static const u8 font[9][8] = {
    { 0x3C, 0x66, 0x66, 0x7E, 0x66, 0x66, 0x66, 0x00 }, // A
    { 0x7E, 0x60, 0x60, 0x7C, 0x60, 0x60, 0x7E, 0x00 }, // E
    { 0x3C, 0x66, 0x60, 0x6E, 0x66, 0x66, 0x3C, 0x00 }, // G
    { 0x66, 0x66, 0x66, 0x7E, 0x66, 0x66, 0x66, 0x00 }, // H
    { 0x60, 0x60, 0x60, 0x60, 0x60, 0x60, 0x7E, 0x00 }, // L
    { 0x3C, 0x66, 0x66, 0x66, 0x66, 0x66, 0x3C, 0x00 }, // O
    { 0x66, 0x66, 0x66, 0x66, 0x66, 0x3C, 0x18, 0x00 }, // V
    { 0x3C, 0x66, 0x60, 0x7C, 0x66, 0x66, 0x3C, 0x00 }, // 6
    { 0x3C, 0x66, 0x66, 0x3C, 0x66, 0x66, 0x3C, 0x00 }, // 8
};

// "HELLO VEGA68" as tile indices (0 = blank)
static const u8 text[12] = { 4, 2, 5, 5, 6, 0, 7, 2, 3, 1, 8, 9 };

void main(void) {
    V68_PALETTE[0] = 0x00102040; // bg: dark blue
    V68_PALETTE[1] = 0x00FFFFFF; // fg: white

    for (i32 g = 0; g < 9; g++)
        for (i32 y = 0; y < 8; y++)
            for (i32 x = 0; x < 8; x++)
                V68_TILES[g + 1].px[y][x] = (font[g][y] >> (7 - x)) & 1;

    for (i32 i = 0; i < 12; i++)
        V68_TILEMAPS[0].cell[11][14 + i] = text[i];
}
